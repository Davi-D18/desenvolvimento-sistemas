double somarPeso(double a, double b) => a + b;

double subtrairTara(double total, double tara) => total - tara;

double multiplicarReceita(double peso, int porcoes) => peso * porcoes;

void main() {
  print(somarPeso(2.5, 3.0));
  print(subtrairTara(10.0, 1.5));
  print(multiplicarReceita(4.0, 3));
}